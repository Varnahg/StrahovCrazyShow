import {readFile,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const gltf=async path=>{const b=await readFile(path);return JSON.parse(b.subarray(20,20+b.readUInt32LE(12)));};
const full=await gltf('public/models/buildings/osm-way-53929057.glb');
const kit=await gltf('public/models/architecture/b4-facade/b4-facade-panels-highest.glb');
const actual=full.materials.find(m=>m.name==='reality B4 grey facade panels');
assert.ok(actual,'Combined B4 material must exist');
const reference=kit.materials.find(m=>m.name.includes('grey panel cladding'));
assert.ok(reference,'Original authored panel material must exist');
const a=actual.pbrMetallicRoughness,r=reference.pbrMetallicRoughness;
for(let i=0;i<4;i++)assert.ok(Math.abs(a.baseColorFactor[i]-r.baseColorFactor[i])<1e-6,'Linear colour matches actual Blender kit');
assert.ok(Math.abs(a.roughnessFactor-.84)<1e-6);
assert.equal(a.metallicFactor,0);
assert.ok(!a.baseColorTexture&&!actual.normalTexture&&!actual.emissiveTexture);
assert.ok(!actual.emissiveFactor||actual.emissiveFactor.every(v=>v===0));
assert.ok(!actual.alphaMode||actual.alphaMode==='OPAQUE');
assert.ok(!actual.doubleSided);
const result={status:'passed',scope:'actual combined B4 GLB compared with actual highest panel-kit GLB',albedo:a.baseColorFactor,roughness:a.roughnessFactor,metallic:a.metallicFactor,textureless:true,emissive:false,checks:['exact linear source colour','native panel roughness','no invented texture or emission','opaque and backface culled']};
await writeFile('docs/reality-pack/separate-assets/b4-combined-material-20261012-m2.json',JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result));
