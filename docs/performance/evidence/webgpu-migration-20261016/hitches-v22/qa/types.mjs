import ts from '../define-order-qa-20261018/dependencies/node_modules/typescript/lib/typescript.js';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root=dirname(fileURLToPath(import.meta.url)),candidate=resolve(root,'candidate');
const config=ts.readConfigFile(resolve(candidate,'tsconfig.json'),ts.sys.readFile);
if(config.error)throw Error(ts.flattenDiagnosticMessageText(config.error.messageText,'\n'));
const options=ts.parseJsonConfigFileContent(config.config,ts.sys,candidate).options;
const names=['client/game.ts','tests/game-light-preparation.test.ts','tests/light-preparation.test.ts','tests/webgpu-compilation-profile.test.ts'];
const program=ts.createProgram(names.map(p=>resolve(candidate,p)),{...options,noEmit:true});
const diagnostics=ts.getPreEmitDiagnostics(program);
console.log(ts.formatDiagnosticsWithColorAndContext(diagnostics,{getCurrentDirectory:()=>candidate,getCanonicalFileName:p=>p,getNewLine:()=> '\n'}));
console.log(JSON.stringify({files:program.getSourceFiles().length,errors:diagnostics.length,scope:names}));
process.exitCode=diagnostics.length?1:0;
